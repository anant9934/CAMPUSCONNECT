class CampusPlaceDirectory:
    """
    In-memory and cached lookup engine for campus places, buildings, blocks,
    categories, and source discrepancies.
    """

    _places_by_id: Dict[str, Dict[str, Any]] = {}
    _places_by_block: Dict[str, Dict[str, Any]] = {}

    @classmethod
    def initialize(cls):
        if not cls._places_by_id:
            for p in MASTER_CAMPUS_PLACES:
                cls._places_by_id[p["place_id"]] = p
                if p["block_number"]:
                    # Normalize block numbers: '32', '01' -> '32', '1'
                    bn = p["block_number"].strip()
                    cls._places_by_block[bn] = p
                    if bn.startswith("0") and len(bn) == 2:
                        cls._places_by_block[bn[1:]] = p

    @classmethod
    def get_all_places(cls) -> List[Dict[str, Any]]:
        cls.initialize()
        return MASTER_CAMPUS_PLACES

    @classmethod
    def get_by_place_id(cls, place_id: str) -> Optional[Dict[str, Any]]:
        cls.initialize()
        return cls._places_by_id.get(place_id.upper()) or cls._places_by_id.get(place_id)

    @classmethod
    def get_by_block_number(cls, block_num: str) -> Optional[Dict[str, Any]]:
        cls.initialize()
        clean = block_num.strip().lower().replace("block", "").replace("blk", "").strip()
        return cls._places_by_block.get(clean) or cls._places_by_block.get(clean.zfill(2))

    @classmethod
    def search_places(
        cls,
        query: str,
        category: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Searches master directory by query matching block number, name, aliases,
        description, facilities, and category.
        """
        cls.initialize()
        q = query.lower().strip()
        results = []

        for p in MASTER_CAMPUS_PLACES:
            if category and p["category"].lower() != category.lower():
                continue

            score = 0.0
            name_low = p["official_name"].lower()
            legend_low = p.get("legend_name", "").lower()
            block_num = (p.get("block_number") or "").lower()
            aliases = [a.lower() for a in p.get("alternative_names", [])]
            desc_low = p["building_description"].lower()

            # Exact block match
            if block_num and (f"block {block_num}" in q or f"blk {block_num}" in q or f"block-{block_num}" in q or q == block_num or q == block_num.lstrip("0")):
                score += 50.0

            # Direct name or legend match
            if name_low in q or q in name_low:
                score += 30.0
            if legend_low and (legend_low in q or q in legend_low):
                score += 25.0

            # Alias match
            for alias in aliases:
                if alias in q or q in alias:
                    score += 20.0
                    break

            # Keyword match in description / category
            if p["category"].lower() in q:
                score += 15.0

            for word in q.split():
                if len(word) >= 3:
                    if word in name_low or any(word in a for a in aliases):
                        score += 5.0
                    elif word in desc_low:
                        score += 2.0

            if score > 0:
                results.append((score, p))

        results.sort(key=lambda x: x[0], reverse=True)
        return [r[1] for r in results]

    @classmethod
    def get_by_category(cls, category: str) -> List[Dict[str, Any]]:
        cls.initialize()
        cat_clean = category.lower().strip()
        matches = []
        for p in MASTER_CAMPUS_PLACES:
            p_cat = p["category"].lower()
            if cat_clean == "all":
                matches.append(p)
            elif cat_clean in p_cat or (cat_clean == "hostel" and "hostel" in p_cat) or (cat_clean == "academic" and "academic" in p_cat):
                matches.append(p)
        return matches

    @classmethod
    def get_discrepancies(cls) -> List[Dict[str, Any]]:
        """Returns all places that have verified discrepancies between site plan and current university records."""
        cls.initialize()
        return [p for p in MASTER_CAMPUS_PLACES if p.get("discrepancy_note")]


# Self-initialize on import
CampusPlaceDirectory.initialize()

